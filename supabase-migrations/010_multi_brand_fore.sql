SET name = EXCLUDED.name, logo_url = EXCLUDED.logo_url, sort_order = EXCLUDED.sort_order;

ALTER TABLE catalog_categories ADD COLUMN IF NOT EXISTS brand_id BIGINT REFERENCES brands(id);
ALTER TABLE catalog_products ADD COLUMN IF NOT EXISTS brand_id BIGINT REFERENCES brands(id);
ALTER TABLE outlets ADD COLUMN IF NOT EXISTS brand_id BIGINT REFERENCES brands(id);

