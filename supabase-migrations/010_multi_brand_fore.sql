ALTER TABLE catalog_categories DROP CONSTRAINT IF EXISTS catalog_categories_source_code_key;
ALTER TABLE catalog_products DROP CONSTRAINT IF EXISTS catalog_products_source_product_id_key;
ALTER TABLE catalog_products DROP CONSTRAINT IF EXISTS catalog_products_product_code_key;
ALTER TABLE outlets DROP CONSTRAINT IF EXISTS outlets_source_id_key;
ALTER TABLE outlets DROP CONSTRAINT IF EXISTS outlets_code_key;

CREATE UNIQUE INDEX IF NOT EXISTS idx_catalog_categories_brand_source
  ON catalog_categories(brand_id, source_code);
CREATE UNIQUE INDEX IF NOT EXISTS idx_catalog_products_brand_source
  ON catalog_products(brand_id, source_product_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_catalog_products_brand_code
  ON catalog_products(brand_id, product_code);
CREATE UNIQUE INDEX IF NOT EXISTS idx_outlets_brand_source
  ON outlets(brand_id, source_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_outlets_brand_code
  ON outlets(brand_id, code);

CREATE INDEX IF NOT EXISTS idx_catalog_categories_brand_active
  ON catalog_categories(brand_id, is_active, sort_order);
CREATE INDEX IF NOT EXISTS idx_catalog_products_brand_active
  ON catalog_products(brand_id, is_active, sort_order);
CREATE INDEX IF NOT EXISTS idx_outlets_brand_active
  ON outlets(brand_id, is_active, name);

DROP TRIGGER IF EXISTS trg_brands_updated_at ON brands;
CREATE TRIGGER trg_brands_updated_at
