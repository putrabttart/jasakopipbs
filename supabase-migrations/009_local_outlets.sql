-- ============================================================
-- Local outlet directory, synchronized from Kopi Kenangan's public website.
-- ============================================================

CREATE TABLE IF NOT EXISTS outlets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id TEXT UNIQUE NOT NULL,
  code TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  country TEXT NOT NULL DEFAULT 'ID',
  city TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '',
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  opening_hours TEXT NOT NULL DEFAULT '',
  is_open BOOLEAN NOT NULL DEFAULT FALSE,
  image_url TEXT NOT NULL DEFAULT '',
  tags JSONB NOT NULL DEFAULT '[]'::jsonb,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  manual_override BOOLEAN NOT NULL DEFAULT FALSE,
  source_payload JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_outlets_country_city
  ON outlets(country, city);
CREATE INDEX IF NOT EXISTS idx_outlets_active_name
  ON outlets(is_active, name);

DROP TRIGGER IF EXISTS trg_outlets_updated_at ON outlets;
CREATE TRIGGER trg_outlets_updated_at
BEFORE UPDATE ON outlets
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE outlets ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE outlets FROM anon, authenticated;

INSERT INTO settings (key, value, updated_at)
VALUES (
  'outlet_sync',
  '{"source_url":"https://kenanganglobal.com/career/kk-hr-career/outlets","last_synced_at":null,"source_updated_at":null}'::jsonb,
  NOW()
)
ON CONFLICT (key) DO NOTHING;
