-- ============================================================
-- Local menu catalog, bootstrapped from Kopi Kenangan's public website feed.
-- ============================================================

CREATE TABLE IF NOT EXISTS catalog_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_code TEXT UNIQUE,
  name TEXT NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  manual_override BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS catalog_products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_product_id TEXT UNIQUE,
  product_code TEXT UNIQUE NOT NULL,
  bundle_code TEXT,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  image_url TEXT NOT NULL DEFAULT '',
  price INTEGER NOT NULL DEFAULT 0 CHECK (price >= 0),
  original_price INTEGER NOT NULL DEFAULT 0 CHECK (original_price >= 0),
  is_promo BOOLEAN NOT NULL DEFAULT FALSE,
  is_combo BOOLEAN NOT NULL DEFAULT FALSE,
  is_sold_out BOOLEAN NOT NULL DEFAULT FALSE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  labels JSONB NOT NULL DEFAULT '[]'::jsonb,
  sort_order INTEGER NOT NULL DEFAULT 0,
  manual_override BOOLEAN NOT NULL DEFAULT FALSE,
  source_payload JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS catalog_product_categories (
  category_id BIGINT NOT NULL REFERENCES catalog_categories(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES catalog_products(id) ON DELETE CASCADE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (category_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_catalog_categories_active_sort
  ON catalog_categories(is_active, sort_order, id);
CREATE INDEX IF NOT EXISTS idx_catalog_products_active_sort
  ON catalog_products(is_active, sort_order, id);
CREATE INDEX IF NOT EXISTS idx_catalog_product_categories_product
  ON catalog_product_categories(product_id);

DROP TRIGGER IF EXISTS trg_catalog_categories_updated_at ON catalog_categories;
CREATE TRIGGER trg_catalog_categories_updated_at
BEFORE UPDATE ON catalog_categories
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_catalog_products_updated_at ON catalog_products;
CREATE TRIGGER trg_catalog_products_updated_at
BEFORE UPDATE ON catalog_products
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

